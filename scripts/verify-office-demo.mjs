import assert from 'node:assert/strict';
const demo = await import('../src/modules/analytics/utils/officeDemo.js').catch(()=>({}));
assert.equal(typeof demo.demoPeople, 'function', 'Demo roster generator must exist');
const members = ['Иванов','Vasya','Gem','Китаец',...Array.from({length:12},(_,i)=>`Member ${i}`)].map((label,i)=>({id:String(i),data:{label}}));
const initial=demo.demoPeople(members,0), later=demo.demoPeople(members,10);
assert.equal(initial.length,16);
assert(initial.every(p=>p.demo===true && !('token' in p)));
assert.deepEqual(members[0],{id:'0',data:{label:'Иванов'}});
assert.equal(demo.avatarTraits('Vasya').beard,true);
assert.equal(demo.avatarTraits('Gem').bald,true);
assert.equal(demo.avatarTraits('Gem').glasses,true);
assert.equal(demo.avatarTraits('Иванов').hookah,true);
for(const action of ['work','eat','sleep','rest','meeting','walk']) assert(initial.some(p=>p.activity===action),action);
assert(initial.some((p,i)=>p.x!==later[i].x || p.z!==later[i].z));
assert(initial.some((p,i)=>p.activity!==demo.demoPeople(members,45)[i].activity),'Activities change over time');
assert(initial.every(p=>Number.isFinite(p.x)&&Number.isFinite(p.z)));
assert.deepEqual(demo.demoPeople([],0),[]);
assert.equal(demo.demoPeople([...members,...members],0).length,16);
const walkerPositions=Array.from({length:150},(_,i)=>demo.demoPeople(members,i)[5]);
assert(new Set(walkerPositions.map(p=>p.x.toFixed(1))).size>2,'Demo walkers should turn along a route, not pace on one line');
console.log('Office demo: roster, isolation, traits, activities and movement passed.');
