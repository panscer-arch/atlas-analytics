const now = "2026-08-11T12:00:00.000Z";

function product(input) {
  return {
    id: input.id,
    slug: input.slug || input.id,
    name: input.name,
    itemType: input.itemType || "PRODUCT",
    parentId: input.parentId || null,
    shortDescription: input.shortDescription || "",
    fullDescription: input.fullDescription || input.shortDescription || "",
    logoUrl: input.logoUrl || "",
    owner: input.owner || "Atlas System",
    executor: input.executor || "",
    responsible: input.responsible || "",
    lifecycleStage: input.lifecycleStage || "IDEA",
    deliveryState: input.deliveryState || "NOT_STARTED",
    availability: input.availability || "NONE",
    priority: input.priority || "MEDIUM",
    currentFocus: input.currentFocus || "",
    nextStep: input.nextStep || "Уточнить следующий контрольный шаг.",
    reviewDate: input.reviewDate || "",
    targetDate: input.targetDate || "",
    blockReason: input.blockReason || "",
    tags: input.tags || [],
    needsConfirmation: Boolean(input.needsConfirmation),
    version: 1,
    lastActivityAt: input.lastActivityAt || now,
    archivedAt: null,
    createdAt: now,
    updatedAt: now,
  };
}

function link(productId, type, label, url, environment = "LIVE", verifiedAt = "") {
  return {
    id: `${productId}-${type.toLowerCase()}`,
    productId,
    type,
    label,
    url,
    environment,
    verifiedAt,
    checkStatus: verifiedAt ? "VERIFIED" : "UNCHECKED",
    createdAt: now,
  };
}

