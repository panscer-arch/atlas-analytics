export function hydrateReelsCampaignState(value) {
  if (!value || typeof value !== "object") return DEFAULT_REELS_CAMPAIGN_STATE;
  return {
    ...DEFAULT_REELS_CAMPAIGN_STATE,
    ...value,
    ideas: Array.isArray(value.ideas)
      ? value.ideas.map((idea) => ({
          ...createEmptyReelsIdea(),
          ...idea,
          metrics: { ...createEmptyReelsIdea().metrics, ...(idea.metrics || {}) },
        }))
      : DEFAULT_REELS_IDEAS,
  };
}

