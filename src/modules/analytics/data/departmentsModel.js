export function buildDepartmentPlan(graph = { nodes: [], edges: [] }) {
  const nodes = Array.isArray(graph.nodes) ? graph.nodes : [];
  const edges = Array.isArray(graph.edges) ? graph.edges : [];
  const memberIds = new Set(
    nodes.filter((n) => n.type === "member").map((n) => n.id),
  );
  return {
    version: 1,
    departments: departments.map(
      ([id, title, scope, gap, next, leaderHint, labels]) => {
        const projectIds = nodes
          .filter((n) => n.type === "project" && labels.includes(n.data?.label))
          .map((n) => n.id);
        return {
          id,
          title,
          scope,
          gap,
          next,
          leaderHint,
          projectIds,
          memberIds: [
            ...new Set(
              edges
                .filter(
                  (e) =>
                    projectIds.includes(e.target) && memberIds.has(e.source),
                )
                .map((e) => e.source),
            ),
          ],
          ownerId: "",
          status: "proposed",
          notes: "",
        };
      },
    ),
    processes: processes.map(
      ([id, departmentId, title, flow, outcome, metric, control]) => ({
        id,
        departmentId,
        title,
        flow,
        outcome,
        metric,
        control,
        ownerId: "",
        status: "proposed",
        next: "Согласовать порядок работы и назначить ответственного.",
        notes: "",
      }),
    ),
    automations: automations.map(
      ([
        id,
        departmentId,
        title,
        priority,
        manual,
        flow,
        control,
        requirements,
        fallback,
      ]) => ({
        id,
        departmentId,
        title,
        priority,
        manual,
        flow,
        control,
        requirements,
        fallback,
        ownerId: "",
        status: "review",
        evidence: "",
        next: "Проверить текущую реализацию и измерить объём ручной работы.",
        notes: "",
      }),
    ),
  };
}

export function validatePlan(value) {
  if (!value || value.version !== 1) return "Неизвестный формат структуры.";
  for (const kind of ["departments", "processes", "automations"]) {
    if (!Array.isArray(value[kind])) return "Повреждён список: " + kind;
    const ids = new Set();
    for (const row of value[kind]) {
      if (
        !row ||
        typeof row.id !== "string" ||
        ids.has(row.id) ||
        typeof row.title !== "string" ||
        !row.title.trim()
      )
        return "Проверьте названия и идентификаторы карточек.";
      ids.add(row.id);
      const statuses = kind === "automations" ? AUTO_STATUSES : PLAN_STATUSES;
      if (!Object.hasOwn(statuses, row.status)) return "Неизвестный статус.";
      if (
        kind === "departments" &&
        (!Array.isArray(row.memberIds) ||
          !Array.isArray(row.projectIds) ||
          ![...row.memberIds, ...row.projectIds].every(
            (id) => typeof id === "string",
          ))
      )
        return "Повреждены назначения отдела.";
      if (typeof row.ownerId !== "string") return "Некорректный ответственный.";
      for (const field of [
        "scope",
        "gap",
        "next",
        "leaderHint",
        "notes",
        "flow",
        "outcome",
        "metric",
        "control",
        "priority",
        "manual",
        "requirements",
        "fallback",
        "evidence",
      ])
        if (row[field] !== undefined && typeof row[field] !== "string")
          return "Некорректное текстовое поле: " + field;
      if (
        kind !== "departments" &&
        !value.departments.some((d) => d.id === row.departmentId)
      )
        return "Укажите существующий отдел.";
      if (row.status === "confirmed" && !row.ownerId)
        return "Для согласования нужен ответственный.";
      if (row.status === "running" && (!row.ownerId || !row.evidence?.trim()))
        return "Для статуса «Работает» нужны ответственный и подтверждение проверки.";
    }
  }
  return "";
}

export function selectRows(rows, query = "", departmentId = "") {
  const needle = query.trim().toLocaleLowerCase("ru");
  return rows.filter(
    (row) =>
      (!departmentId || (row.departmentId || row.id) === departmentId) &&
      (!needle ||
        Object.values(row)
          .filter((v) => typeof v === "string")
          .join(" ")
          .toLocaleLowerCase("ru")
          .includes(needle)),
  );
}

// The existing content API has no atomic revisions for this key. Preflight
// catches already changed snapshots; it is not a multi-editor transaction lock.
export async function savePlanSafely(plan, baseline, { load, save }) {
  const error = validatePlan(plan);
  if (error) return { ok: false, error };
  const current = await load();
  if (!current.ok)
    return {
      ok: false,
      error: "Сервер недоступен. Изменения остаются в этой вкладке.",
    };
  if (
    JSON.stringify(current.exists ? current.value : null) !==
    JSON.stringify(baseline)
  )
    return {
      ok: false,
      error:
        "На сервере другая версия. Экспортируйте свой черновик и перечитайте серверную версию.",
    };
  if (!(await save(plan)))
    return {
      ok: false,
      error: "Сохранение не подтверждено. Изменения остаются в этой вкладке.",
    };
  const verified = await load();
  if (
    !verified.ok ||
    !verified.exists ||
    JSON.stringify(verified.value) !== JSON.stringify(plan)
  )
    return {
      ok: false,
      error:
        "Не удалось подтвердить сохранение чтением. Экспортируйте черновик перед перезагрузкой.",
    };
  return { ok: true };
}
