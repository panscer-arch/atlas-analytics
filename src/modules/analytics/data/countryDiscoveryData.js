export function createCountryDiscoverySearchUrl(country, query, platform) {
  const domains = {
    Instagram: "instagram.com",
    "Facebook Groups": "facebook.com/groups",
    Facebook: "facebook.com",
    TikTok: "tiktok.com",
    YouTube: "youtube.com",
    LinkedIn: "linkedin.com/in",
    Telegram: "t.me",
    VK: "vk.com",
    Naver: "naver.com",
    WeChat: "weixin.qq.com",
    Zalo: "zalo.me",
  };
  const domain = domains[platform];
  const search = [domain ? `site:${domain}` : "", query, country.countryEn].filter(Boolean).join(" ");
  return `https://www.google.com/search?q=${encodeURIComponent(search)}`;
}
