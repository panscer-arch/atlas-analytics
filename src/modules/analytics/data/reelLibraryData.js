export const reelLibrarySeeds = [
  ...defaultToolRadarItems.filter((item) => /(^|\.)instagram\.com$|(^|\.)threads\.com$/.test(new URL(item.sourceUrl).hostname)),
  ...reviewedReelItems,
];

function sourceKey(sourceUrl) {
  try {
    const url = new URL(sourceUrl);
    return `${url.hostname.replace(/^www\./, "")}${url.pathname.replace(/\/$/, "")}`;
  } catch {
    return String(sourceUrl || "").trim();
  }
}

export function mergeReelLibraryItems(savedItems) {
  if (!Array.isArray(savedItems)) return reelLibrarySeeds;
  const saved = savedItems.filter((item) => item && typeof item === "object");
  const ids = new Set(saved.map((item) => item.id));
  const sources = new Set(saved.map((item) => sourceKey(item.sourceUrl)));
  return [
    ...saved,
    ...reelLibrarySeeds.filter((item) => !ids.has(item.id) && !sources.has(sourceKey(item.sourceUrl))),
  ];
}
